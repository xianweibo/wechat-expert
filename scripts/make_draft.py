def call_minimax(system, user, model="MiniMax-M2.7", max_tokens=4096):
    body = json.dumps({
        "model": model,
        "max_tokens": max_tokens,
        "system": system,
        "messages": [{"role": "user", "content": user}],
    }, ensure_ascii=False).encode("utf-8")
    conn = http.client.HTTPSConnection("api.minimaxi.com", timeout=240)
    conn.request(
        "POST", "/anthropic/v1/messages", body=body,
        headers={
            "x-api-key": MINIMAX_KEY,
            "anthropic-version": "2023-06-01",
            "Content-Type": "application/json; charset=utf-8",
        },
    )
    resp = conn.getresponse()
    data = resp.read().decode("utf-8")
    conn.close()
    obj = json.loads(data)
    parts = []
    for c in obj.get("content", []):
        if isinstance(c, dict) and c.get("type") == "text":
            parts.append(c.get("text", ""))
    return "".join(parts)


