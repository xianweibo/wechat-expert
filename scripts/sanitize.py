    (r'逢高减仓|逢低加仓|高抛低吸|止损位', '（历史回测数据）'),
    (r'第[一二三四5]\s*目标位|看到\d{3,5}\s*点', '（历史区间参考）'),
    (r'上车了|抄底了|上车机会|加仓机会', '（按个人判断）'),
    (r'不要错过|不容错过|最后机会|抓紧时间上车', '（个人研究参考）'),
    (r'可以买|可以卖|值得买|值得入手', '（历史数据观察）'),
    (r'上方阻力\s*位?[\d.]+|下方支撑\s*位?[\d.]+', '对应历史阻力/支撑区域'),

    # === B. 绝对收益承诺 ===
    (r'稳赚不赔|必赚|包赚|保本收益|无风险收益', '（历史回测记录）'),
    (r'必涨|必跌|必崩|必翻倍|必翻番|翻倍牛', '（历史区间参考）'),
    (r'年化(\d{1,3})[%％]以上?稳[定不]?赚|年化(\d{1,3})[%％]稳[定不]?亏', '历史年化参考区间'),
    (r'一定会涨|一定会跌|肯定涨|肯定跌|一定[跌涨翻]到\d', '（历史概率分布）'),
