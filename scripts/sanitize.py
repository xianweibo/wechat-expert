    (r'收益(\d{2,4})[%％]|盈利(\d{2,4})[%％]', '历史收益区间参考'),

    # === C. 煽动/恐慌 + 地缘高敏 ===
    (r'去美元化', '国际货币格局多元化'),
    (r'本币结算', '非美元货币结算'),
    (r'替代支付系统', '跨境支付新渠道'),
