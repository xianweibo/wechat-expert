def sanitize_text(text):
    """对文本执行所有消毒规则, 返回替换后文本+命中数。"""
    if not text:
        return text, 0
    count = 0
    for pattern, repl in SANITIZE_RULES:
        new_text, n = re.subn(pattern, repl, text)
        if n > 0:
            count += n
            text = new_text
    return text, count


