    (r'切记[，。]?\s*(空|多|加仓|减仓|清仓|平仓|建仓|满仓)', '（历史数据记录，非操作建议）'),
    (r'(空|多|加仓|减仓|清仓|平仓|建仓|满仓)[，,]?\s*或\s*(\d)\s*层', '（仓位仅为历史回测记录）'),
